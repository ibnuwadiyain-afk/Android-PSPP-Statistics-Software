package org.pspp.mobile.engine

import org.pspp.mobile.model.AnalysisProcedure
import org.pspp.mobile.model.PsppDataset
import org.pspp.mobile.model.TTestMode
import org.pspp.mobile.model.VariableType

/**
 * Generates canonical GNU PSPP 2.1.2 syntax (.sps) for all 9 statistical analysis
 * procedures as well as full dataset definition and dictionary synchronization.
 */
object PsppSyntaxGenerator {

    fun generateDatasetSyntax(dataset: PsppDataset, includeInlineData: Boolean = true): String {
        val sb = StringBuilder()
        sb.appendLine("* =========================================================================")
        sb.appendLine("* Generated by PSPP Studio — Active Dataset: ${dataset.name}")
        sb.appendLine("* Cases: ${dataset.caseCount} | Variables: ${dataset.variableCount}")
        sb.appendLine("* =========================================================================")
        sb.appendLine()

        if (includeInlineData && dataset.variables.isNotEmpty()) {
            sb.appendLine("DATA LIST FREE /")
            dataset.variables.forEach { v ->
                sb.appendLine("  ${v.name} (${v.formatSpec()})")
            }
            sb.appendLine(".")
            sb.appendLine()
        }

        val labeledVars = dataset.variables.filter { it.label.isNotBlank() }
        if (labeledVars.isNotEmpty()) {
            sb.appendLine("VARIABLE LABELS")
            labeledVars.forEachIndexed { idx, v ->
                val term = if (idx == labeledVars.lastIndex) "." else ""
                sb.appendLine("  ${v.name} '${v.label.replace("'", "''")}'$term")
            }
            sb.appendLine()
        }

        val valLabelVars = dataset.variables.filter { it.valueLabels.isNotEmpty() }
        if (valLabelVars.isNotEmpty()) {
            sb.appendLine("VALUE LABELS")
            valLabelVars.forEachIndexed { idx, v ->
                val pairs = v.valueLabels.entries.joinToString(" ") { (k, label) ->
                    val keyFormatted = if (v.type == VariableType.STRING) "'$k'" else k
                    "$keyFormatted '${label.replace("'", "''")}'"
                }
                val prefix = if (idx == 0) "  " else "  /"
                val term = if (idx == valLabelVars.lastIndex) "." else ""
                sb.appendLine("$prefix${v.name} $pairs$term")
            }
            sb.appendLine()
        }

        val missingVars = dataset.variables.filter { it.missingValues.isNotEmpty() }
        if (missingVars.isNotEmpty()) {
            sb.appendLine("MISSING VALUES")
            missingVars.forEachIndexed { idx, v ->
                val vals = v.missingValues.joinToString(", ")
                val term = if (idx == missingVars.lastIndex) "." else ""
                sb.appendLine("  ${v.name} ($vals)$term")
            }
            sb.appendLine()
        }

        if (dataset.variables.isNotEmpty()) {
            sb.appendLine("VARIABLE LEVEL")
            dataset.variables.forEachIndexed { idx, v ->
                val prefix = if (idx == 0) "  " else "  /"
                val term = if (idx == dataset.variables.lastIndex) "." else ""
                sb.appendLine("$prefix${v.name} (${v.measure.psppKeyword})$term")
            }
            sb.appendLine()
        }

        if (includeInlineData && dataset.rows.isNotEmpty()) {
            sb.appendLine("BEGIN DATA")
            dataset.rows.forEach { row ->
                val formattedCells = dataset.variables.mapIndexed { idx, v ->
                    val raw = row.getOrNull(idx)?.trim().orEmpty()
                    if (raw.isEmpty()) "."
                    else if (v.type == VariableType.STRING) "'${raw.replace("'", "''")}'"
                    else raw
                }
                sb.appendLine(formattedCells.joinToString(" "))
            }
            sb.appendLine("END DATA.")
            sb.appendLine()
        }

        sb.appendLine("DISPLAY DICTIONARY.")
        sb.appendLine("DESCRIPTIVES VARIABLES=${dataset.variables.filter { it.type != VariableType.STRING }.take(5).joinToString(" ") { it.name }}.")
        sb.appendLine("EXECUTE.")
        return sb.toString()
    }

    fun generateProcedureSyntax(
        procedure: AnalysisProcedure,
        selectedVars: List<String>,
        secondaryVar: String = "",
        ttestMode: TTestMode = TTestMode.INDEPENDENT,
        groupVal1: String = "1",
        groupVal2: String = "2",
        includeExtraStats: Boolean = true
    ): String {
        val varsClause = selectedVars.ifEmpty { listOf("baseline_bp", "followup_bp", "outcome_score") }.joinToString(" ")
        val second = secondaryVar.ifBlank { "group" }

        return when (procedure) {
            AnalysisProcedure.DESCRIPTIVES -> buildString {
                appendLine("* Descriptive Statistics Procedure")
                appendLine("DESCRIPTIVES VARIABLES=$varsClause")
                if (includeExtraStats) {
                    appendLine("  /STATISTICS=MEAN STDDEV MIN MAX VARIANCE SKEWNESS KURTOSIS SEMEAN.")
                } else {
                    appendLine("  /STATISTICS=MEAN STDDEV MIN MAX.")
                }
                appendLine("EXECUTE.")
            }

            AnalysisProcedure.FREQUENCIES -> buildString {
                appendLine("* Frequencies & Summary Quantiles Procedure")
                appendLine("FREQUENCIES VARIABLES=$varsClause")
                appendLine("  /FORMAT=AVALUE TABLE")
                if (includeExtraStats) {
                    appendLine("  /STATISTICS=MEAN STDDEV MEDIAN MODE MIN MAX")
                    appendLine("  /BARCHART.")
                } else {
                    appendLine("  /STATISTICS=MEAN STDDEV MIN MAX.")
                }
                appendLine("EXECUTE.")
            }

            AnalysisProcedure.CROSSTABS -> {
                val rowVar = selectedVars.firstOrNull() ?: "group"
                val colVar = secondaryVar.ifBlank { selectedVars.getOrNull(1) ?: "gender" }
                buildString {
                    appendLine("* Contingency Table (Crosstabs) & Chi-Square Test")
                    appendLine("CROSSTABS")
                    appendLine("  /TABLES=$rowVar BY $colVar")
                    appendLine("  /FORMAT=AVALUE TABLES")
                    appendLine("  /STATISTICS=CHISQ PHI")
                    appendLine("  /CELLS=COUNT ROW COLUMN TOTAL.")
                    appendLine("EXECUTE.")
                }
            }

            AnalysisProcedure.TTEST -> {
                if (ttestMode == TTestMode.INDEPENDENT) {
                    buildString {
                        appendLine("* Independent-Samples T-Test")
                        appendLine("T-TEST GROUPS=$second($groupVal1, $groupVal2)")
                        appendLine("  /VARIABLES=$varsClause")
                        appendLine("  /CRITERIA=CI(0.95).")
                        appendLine("EXECUTE.")
                    }
                } else {
                    val v1 = selectedVars.firstOrNull() ?: "baseline_bp"
                    val v2 = secondaryVar.ifBlank { selectedVars.getOrNull(1) ?: "followup_bp" }
                    buildString {
                        appendLine("* Paired-Samples T-Test")
                        appendLine("T-TEST PAIRS=$v1 WITH $v2 (PAIRED)")
                        appendLine("  /CRITERIA=CI(0.95).")
                        appendLine("EXECUTE.")
                    }
                }
            }

            AnalysisProcedure.ANOVA -> buildString {
                appendLine("* One-Way Analysis of Variance (ANOVA)")
                appendLine("ONEWAY $varsClause BY $second")
                if (includeExtraStats) {
                    appendLine("  /STATISTICS=DESCRIPTIVES HOMOGENEITY")
                    appendLine("  /POSTHOC=TUKEY BONFERRONI.")
                } else {
                    appendLine("  /STATISTICS=DESCRIPTIVES.")
                }
                appendLine("EXECUTE.")
            }

            AnalysisProcedure.CORRELATION -> buildString {
                appendLine("* Bivariate Pearson Correlation Matrix")
                appendLine("CORRELATIONS")
                appendLine("  /VARIABLES=$varsClause")
                appendLine("  /PRINT=TWOTAIL NOSIG")
                if (includeExtraStats) {
                    appendLine("  /STATISTICS=DESCRIPTIVES.")
                } else {
                    appendLine("  .")
                }
                appendLine("EXECUTE.")
            }

            AnalysisProcedure.REGRESSION -> {
                val depVar = secondaryVar.ifBlank { "outcome_score" }
                val indepVars = selectedVars.filter { it != depVar }.ifEmpty { listOf("adherence_score", "baseline_bp", "age") }
                val allRegVars = (indepVars + depVar).distinct().joinToString(" ")
                buildString {
                    appendLine("* Ordinary Least Squares (OLS) Multiple Linear Regression")
                    appendLine("REGRESSION")
                    appendLine("  /VARIABLES=$allRegVars")
                    appendLine("  /DEPENDENT=$depVar")
                    appendLine("  /METHOD=ENTER")
                    appendLine("  /STATISTICS=COEFF R ANOVA CI.")
                    appendLine("EXECUTE.")
                }
            }

            AnalysisProcedure.CHISQUARE -> buildString {
                appendLine("* Nonparametric Chi-Square Goodness-of-Fit Test")
                appendLine("NPAR TESTS")
                appendLine("  /CHISQUARE=$varsClause")
                appendLine("  /EXPECTED=EQUAL.")
                appendLine("EXECUTE.")
            }

            AnalysisProcedure.RELIABILITY -> {
                val relVars = selectedVars.ifEmpty { listOf("qol_item1", "qol_item2", "qol_item3", "qol_item4") }.joinToString(" ")
                buildString {
                    appendLine("* Scale Reliability Analysis (Cronbach's Alpha)")
                    appendLine("RELIABILITY")
                    appendLine("  /VARIABLES=$relVars")
                    appendLine("  /SCALE('Scale All Variables') ALL")
                    appendLine("  /MODEL=ALPHA")
                    appendLine("  /SUMMARY=TOTAL.")
                    appendLine("EXECUTE.")
                }
            }
        }
    }
}
